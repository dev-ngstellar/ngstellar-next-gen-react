export const getProfessionById = (id) => {
  const normId = id?.toLowerCase();
  
  // Custom mappings to handle slug variations from themes list
  const mappings = {
    'cyber-security-expert': 'cyber-security',
    'founder': 'startup-founder',
    'consultant': 'business-consultant',
  };
  
  const mappedId = mappings[normId] || normId;
  return professions.find((p) => p.id === mappedId);
};

export const getProfessionsByCategory = (category) =>
  category === 'all'
    ? professions
    : professions.filter((p) => p.category === category);

export const getFeaturedProfessions = () =>
  professions.filter((p) => p.featured);

