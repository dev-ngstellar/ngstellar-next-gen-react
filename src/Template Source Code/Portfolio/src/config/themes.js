export const defaultTheme = 'developer-dark';

export const getThemeById = (id) =>
  themes.find((t) => t.id === id) || themes[0];

export const applyTheme = (theme) => {
  const root = document.documentElement;
  const c = theme.colors;
  root.style.setProperty('--color-primary', c.primary);
  root.style.setProperty('--color-primary-light', c.primaryLight);
  root.style.setProperty('--color-primary-dark', c.primaryDark);
  root.style.setProperty('--color-secondary', c.secondary);
  root.style.setProperty('--color-accent', c.accent);
  root.style.setProperty('--color-accent-light', c.accentLight);
  root.style.setProperty('--color-bg', c.background);
  root.style.setProperty('--color-surface', c.surface);
  root.style.setProperty('--color-surface-alt', c.surfaceAlt);
  root.style.setProperty('--color-text', c.text);
  root.style.setProperty('--color-text-muted', c.textMuted);
  root.style.setProperty('--color-text-subtle', c.textSubtle);
  root.style.setProperty('--color-border', c.border);
  root.style.setProperty('--gradient-hero', c.heroGradient);
  root.style.setProperty('--gradient-card', c.cardGradient);
  root.style.setProperty('--color-glow', c.glowColor);
  root.setAttribute('data-theme', theme.id);
  root.setAttribute('data-dark', theme.isDark ? 'true' : 'false');
};
